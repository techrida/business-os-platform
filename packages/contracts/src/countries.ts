/** An ISO 3166-1 alpha-2 country code. */
export const CountryCodeSchema = z.enum(ISO_COUNTRIES);
export type CountryCode = z.infer<typeof CountryCodeSchema>;

/** The country a new party, address or phone row starts with. */
export const DEFAULT_COUNTRY: CountryCode = 'NP';

/** Whether `value` is one of the ISO codes. */
export function isCountryCode(value: string): value is CountryCode {
  return CountryCodeSchema.safeParse(value).success;
}

/** The calling code of `code` without the plus sign (`'977'` for NP), or null for a territory with none (AQ, BV). */
export function countryCallingCode(code: CountryCode): string | null {
  if (!isSupportedCountry(code)) return null;
  return getCountryCallingCode(code);
}

const displayNames = new Map<string, Intl.DisplayNames>();

/** The country's name in `locale` (`'Nepal'`), or the code itself when the runtime has no name for it. */
export function countryName(code: CountryCode, locale = 'en'): string {
  let names = displayNames.get(locale);
  if (names === undefined) {
    names = new Intl.DisplayNames([locale], { type: 'region' });
    displayNames.set(locale, names);
  }
  return names.of(code) ?? code;
}

/** The countries a phone number can belong to (those with a calling code), in ISO order. */
export function countriesWithDialCode(): CountryCode[] {
  return ISO_COUNTRIES.filter((code) => countryCallingCode(code) !== null);
}
